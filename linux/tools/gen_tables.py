#!/usr/bin/env python3
"""Regenerate kvtables.py from the Rust source of truth (src/mapping.rs).

    python3 tools/gen_tables.py ../src/mapping.rs > kvtables.py

The Linux engine must never carry its own hand-typed copy of the tables: this
script reads VOWELS, CONSONANTS, SIGNS and ACCENTS straight out of mapping.rs.
"""
import re, sys, ast

src = open(sys.argv[1], encoding="utf-8").read()

def block(name):
    m = re.search(r"pub static %s:[^=]*=\s*&\[(.*?)\n\];" % name, src, re.S)
    if not m:
        sys.exit("cannot find %s in mapping.rs" % name)
    return m.group(1)

def code(rest):
    """Rust char / str literal with \\u{..} escapes -> Python str."""
    rest = rest.strip()
    q = rest[0]
    body = rest[1:rest.rindex(q)]
    body = re.sub(r"\\u\{([0-9A-Fa-f]+)\}", lambda m: chr(int(m.group(1), 16)), body)
    return body

def keys(s):
    return ast.literal_eval("[" + s + "]")

vowels = []
for line in block("VOWELS").splitlines():
    line = line.split("//")[0].strip()
    m = re.match(r"\(&\[(.*?)\],\s*('(?:[^'\\]|\\.)*'),\s*(None|Some\(('(?:[^'\\]|\\.)*')\))\),?$", line)
    if m:
        vowels.append((keys(m.group(1)), code(m.group(2)), None if m.group(3) == "None" else code(m.group(4))))

cons = []
for line in block("CONSONANTS").splitlines():
    line = line.split("//")[0].strip()
    m = re.match(r'\(&\[(.*?)\],\s*("(?:[^"\\]|\\.)*")\),?$', line)
    if m:
        cons.append((keys(m.group(1)), code(m.group(2))))

signs = []
m = re.search(r"pub static SIGNS:[^=]*=\s*&\[(.*?)\];", src, re.S)
consts = dict(re.findall(r"pub const (\w+): char = '\\u\{([0-9A-Fa-f]+)\}'", src))
for k, name in re.findall(r"\(&\[(.*?)\],\s*(\w+)\)", m.group(1)):
    signs.append((keys(k), chr(int(consts[name], 16))))

accents = []
for line in block("ACCENTS").splitlines():
    line = line.split("//")[0].strip()
    m = re.match(r"\(&\[(.*)\],\s*(\w+),\s*\"[^\"]*\"\),?$", line)
    if m:
        accents.append((keys(m.group(1)), chr(int(consts[m.group(2)], 16))))

others = []
m = re.search(r"pub static OTHERS:[^=]*=\s*&\[(.*?)\n\];", src, re.S)
for line in m.group(1).splitlines():
    line = line.split("//")[0].strip()
    mm = re.match(r"\(&\[(.*?)\],\s*('(?:[^'\\]|\\.)*')\),?$", line)
    if mm:
        others.append((keys(mm.group(1)), code(mm.group(2))))

agama = chr(int(re.search(r"pub const AGAMA_ANUSVARA: char = '\\u\{([0-9A-Fa-f]+)\}'", src).group(1), 16))
brk = re.search(r'pub const BREAK_KEY: &str = "(.*?)";', src).group(1)

print("# GENERATED by tools/gen_tables.py from src/mapping.rs. Do not edit by hand.")
print("VOWELS = %r" % (vowels,))
print("CONSONANTS = %r" % (cons,))
print("SIGNS = %r" % (signs,))
print("ACCENTS = %r" % (accents,))
print("OTHERS = %r" % (others,))
print("NUKTA = %r" % chr(int(consts["NUKTA"], 16)))
print("VIRAMA = %r" % chr(int(consts["VIRAMA"], 16)))
print("ANUSVARA = %r" % chr(int(consts["ANUSVARA"], 16)))
print("VISARGA = %r" % chr(int(consts["VISARGA"], 16)))
print("AGAMA_ANUSVARA = %r" % agama)
print("BREAK_KEY = %r" % brk)
